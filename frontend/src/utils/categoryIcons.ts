/**
 * Icon for a configured or historical category. A valid explicit choice wins;
 * otherwise built-in names keep their familiar icon and everything else falls
 * back to the generic tag.
 */
export function categoryIcon(
  category: string,
  icon?: CategoryIconId,
): Component {
  if (isCategoryIconId(icon)) {
    const explicit = CATEGORY_ICON_OPTIONS.find((option) => option.id === icon)
    if (explicit) return explicit.component
  }
  if (!Object.prototype.hasOwnProperty.call(CATEGORY_ICONS, category)) {
    return PriceTag
  }
  return CATEGORY_ICONS[category] ?? PriceTag
}
