CREATE TABLE households (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL CHECK (char_length(name) BETWEEN 1 AND 100),
    invite_code TEXT NOT NULL CHECK (char_length(invite_code) BETWEEN 1 AND 128),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT households_invite_code_key UNIQUE (invite_code)
);

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL CHECK (char_length(username) BETWEEN 1 AND 150),
    password_hash TEXT NOT NULL,
    household_id BIGINT NOT NULL REFERENCES households (id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT users_username_key UNIQUE (username),
    CONSTRAINT users_id_household_key UNIQUE (id, household_id)
);

CREATE INDEX users_household_id_idx ON users (household_id, id);

CREATE TABLE accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id BIGINT NOT NULL REFERENCES households (id) ON DELETE CASCADE,
    name TEXT NOT NULL CHECK (char_length(name) BETWEEN 1 AND 100),
    opening_balance_cents BIGINT NOT NULL DEFAULT 0
        CHECK (opening_balance_cents BETWEEN -999999999999 AND 999999999999),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT accounts_id_household_key UNIQUE (id, household_id)
);

CREATE INDEX accounts_household_id_idx ON accounts (household_id, id);

CREATE TABLE transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id BIGINT NOT NULL REFERENCES households (id) ON DELETE CASCADE,
    account_id BIGINT NOT NULL,
    kind TEXT NOT NULL CHECK (kind IN ('income', 'expense')),
    amount_cents BIGINT NOT NULL CHECK (amount_cents > 0 AND amount_cents <= 999999999999),
    category TEXT NOT NULL CHECK (char_length(category) BETWEEN 1 AND 64),
    tx_date DATE NOT NULL,
    note TEXT NOT NULL DEFAULT '',
    created_by BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT transactions_account_fk
        FOREIGN KEY (account_id, household_id)
        REFERENCES accounts (id, household_id) ON DELETE CASCADE,
    CONSTRAINT transactions_created_by_fk
        FOREIGN KEY (created_by, household_id)
        REFERENCES users (id, household_id) ON DELETE CASCADE
);

CREATE INDEX transactions_household_date_idx
    ON transactions (household_id, tx_date DESC, id DESC);
CREATE INDEX transactions_account_date_idx
    ON transactions (account_id, tx_date);
CREATE INDEX transactions_household_kind_idx
    ON transactions (household_id, kind);

CREATE TABLE sessions (
    token_hash BYTEA PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX sessions_user_id_idx ON sessions (user_id);
CREATE INDEX sessions_expires_at_idx ON sessions (expires_at);
